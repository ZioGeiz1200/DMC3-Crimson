#!/usr/bin/env python3
"""Subset a Chinese TTF to the characters used by the translation and emit an ImGui-ready header.

Usage:
    python tools/gen_cjk_font.py --font tools/font.ttf --chars tools/used_chars.txt \
        --out src/Fonts/CJKSubset.hpp

Requires: pip install fonttools
"""
import argparse
import io

from fontTools import subset
from fontTools.ttLib import TTFont


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True, help="source TTF (must use glyf outlines, not CFF/OTF)")
    ap.add_argument("--chars", required=True, help="UTF-8 text file with every character to keep")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    text = open(args.chars, encoding="utf-8").read()
    codepoints = sorted({ord(c) for c in text if ord(c) >= 0x20})
    if not codepoints:
        raise SystemExit("character set is empty")

    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.drop_tables += ["DSIG"]

    font = subset.load_font(args.font, options)
    if "CFF " in font:
        raise SystemExit(
            "this font uses CFF outlines (OTF); stb_truetype cannot rasterize it. "
            "Use a TTF build (e.g. a Source Han Sans TTF conversion, LXGW WenKai, HarmonyOS Sans SC)."
        )
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)

    buf = io.BytesIO()
    font.flavor = None
    font.save(buf)
    data = buf.getvalue()

    ranges = []
    start = prev = codepoints[0]
    for cp in codepoints[1:]:
        if cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
    ranges.append((start, prev))
    ranges.append((0, 0))

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by tools/gen_cjk_font.py. Do not edit.\n")
        f.write("#pragma once\n\n")
        f.write("static const unsigned char CJKSubset_data[] = {\n")
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]))
            f.write(",\n")
        f.write("};\n")
        f.write(f"static const unsigned int CJKSubset_size = {len(data)}u;\n\n")
        f.write("static const unsigned short CJKSubset_ranges[] = {\n")
        for lo, hi in ranges:
            f.write(f"{lo},{hi},\n")
        f.write("};\n")

    print(f"subset bytes: {len(data)}  glyphs: {len(codepoints)}  ranges: {len(ranges) - 1}")


if __name__ == "__main__":
    main()
